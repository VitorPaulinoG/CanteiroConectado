package br.com.canteiroconectado.exception;

import org.springframework.http.HttpStatus;

public enum ErrorCode {

    VALIDACAO_INVALIDA(HttpStatus.BAD_REQUEST),
    NAO_AUTENTICADO(HttpStatus.UNAUTHORIZED),
    ACESSO_NEGADO(HttpStatus.FORBIDDEN),
    RECURSO_NAO_ENCONTRADO(HttpStatus.NOT_FOUND),
    METODO_NAO_PERMITIDO(HttpStatus.METHOD_NOT_ALLOWED),
    CONFLITO(HttpStatus.CONFLICT),
    ERRO_INESPERADO(HttpStatus.INTERNAL_SERVER_ERROR),
    CREDENCIAIS_INVALIDAS(HttpStatus.UNAUTHORIZED),
    USUARIO_INATIVO(HttpStatus.FORBIDDEN),
    CONTA_BLOQUEADA(HttpStatus.LOCKED),
    SENHA_ATUAL_INCORRETA(HttpStatus.UNPROCESSABLE_CONTENT),
    SENHA_FRACA(HttpStatus.UNPROCESSABLE_CONTENT),
    SENHA_IGUAL_A_ATUAL(HttpStatus.UNPROCESSABLE_CONTENT),
    TROCA_DE_SENHA_OBRIGATORIA(HttpStatus.FORBIDDEN),
    CANTEIRO_DUPLICADO(HttpStatus.CONFLICT),
    CANTEIRO_INATIVO(HttpStatus.UNPROCESSABLE_CONTENT),
    EMAIL_JA_CADASTRADO(HttpStatus.CONFLICT),
    CANTEIRO_OBRIGATORIO(HttpStatus.UNPROCESSABLE_CONTENT),
    AUTODESATIVACAO_PROIBIDA(HttpStatus.UNPROCESSABLE_CONTENT),
    ADMINISTRADOR_PROTEGIDO(HttpStatus.UNPROCESSABLE_CONTENT),
    CREDENCIAL_JA_TROCADA(HttpStatus.CONFLICT),
    COLABORADOR_DUPLICADO(HttpStatus.CONFLICT),
    COLABORADOR_INVALIDO(HttpStatus.UNPROCESSABLE_CONTENT),
    CODIGO_DUPLICADO(HttpStatus.CONFLICT),
    ITEM_JA_MOVIMENTADO(HttpStatus.UNPROCESSABLE_CONTENT),
    ITEM_INATIVO(HttpStatus.UNPROCESSABLE_CONTENT),
    SALDO_INSUFICIENTE(HttpStatus.UNPROCESSABLE_CONTENT),
    QUANTIDADE_INVALIDA(HttpStatus.UNPROCESSABLE_CONTENT);

    private final HttpStatus statusPadrao;

    ErrorCode(HttpStatus statusPadrao) {
        this.statusPadrao = statusPadrao;
    }

    public HttpStatus statusPadrao() {
        return statusPadrao;
    }
}
